export interface Sprite {
  canvas: HTMLCanvasElement;
  w: number;
  h: number;
}

const cache = new Map<SpriteId, Sprite>();

/** The sprite as a ready canvas, painted on first use. */
export function sprite(id: SpriteId): Sprite {
  const hit = cache.get(id);
  if (hit) return hit;
  const rows = ART[id];
  const w = Math.max(...rows.map((r) => r.length));
  const canvas = document.createElement("canvas");
  canvas.width = w;
  canvas.height = rows.length;
  const g = canvas.getContext("2d")!;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = PALETTE[row[x]];
      if (!c) continue;
      g.fillStyle = c;
      g.fillRect(x, y, 1, 1);
    }
  });
  const made = { canvas, w, h: rows.length };
  cache.set(id, made);
  return made;
}

